#!/usr/bin/env node
// Generate migrations/0002_seed.sql from src/01-data.js.
// Zero dependencies. The source is loaded with a real dynamic import() (a data:
// URL module is used because 01-data.js is written for the browser and is not
// itself an ES module at baseline).

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import path from 'node:path';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const DATA_FILE = path.join(ROOT, 'src', '01-data.js');
const OUT_FILE = path.join(ROOT, 'migrations', '0002_seed.sql');

// Fixed timestamp keeps the generated migration deterministic across runs.
const SEED_AT = Date.UTC(2026, 9, 23, 0, 0, 0);

export async function loadSourceData() {
  let source = await readFile(DATA_FILE, 'utf8');

  // The browser file currently declares consts without exports. Add exports for
  // this isolated copy only; source files are never modified.
  if (!/\bexport\s*\{[^}]*\bISLANDS\b/.test(source) &&
      !/\bexport\s+const\s+ISLANDS\b/.test(source)) {
    source += '\nexport { ISLANDS, ITEMS, FLOWS };\n';
  }

  // Minimal browser-runtime surface used by the top level of 01-data.js.
  if (typeof globalThis.location === 'undefined') {
    globalThis.location = { search: '' };
  }
  if (typeof globalThis.THREE === 'undefined') {
    globalThis.THREE = {
      Vector2: class Vector2 {
        constructor(x = 0, y = 0) { this.x = x; this.y = y; }
      },
    };
  }

  const url = 'data:text/javascript;base64,' + Buffer.from(source, 'utf8').toString('base64');
  const mod = await import(url);
  if (!Array.isArray(mod.ISLANDS) || !mod.ITEMS || !Array.isArray(mod.FLOWS)) {
    throw new Error('src/01-data.js did not expose ISLANDS / ITEMS / FLOWS');
  }
  return { ISLANDS: mod.ISLANDS, ITEMS: mod.ITEMS, FLOWS: mod.FLOWS };
}

function literal(value) {
  if (value === null || value === undefined) return 'NULL';
  const text = String(value).replace(/\r\n?/g, '\n').replace(/'/g, "''");
  if (!text.includes('\n')) return `'${text}'`;
  // Keep newlines explicit and valid even for line-oriented SQL tooling.
  return text.split('\n').map((part) => `'${part}'`).join(' || char(10) || ');
}

function jsonLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  return literal(JSON.stringify(value));
}

export async function buildSeedSQL() {
  const { ISLANDS, ITEMS, FLOWS } = await loadSourceData();
  const itemEntries = Object.entries(ITEMS);
  const lines = [];

  lines.push('-- AUTO-GENERATED by scripts/gen-seed.mjs — do not edit by hand.');
  lines.push(`-- Source: src/01-data.js · generated_at=${new Date(SEED_AT).toISOString()}`);
  lines.push(`-- Counts: islands=${ISLANDS.length} items=${itemEntries.length} flows=${FLOWS.length}`);
  lines.push('');

  lines.push('-- islands');
  for (const island of ISLANDS) {
    lines.push(
      'INSERT OR REPLACE INTO islands ' +
      '(id, no, theme, name_zh, name_en, summary_zh, summary_en, icon, color, ang, radius, origin, news_id, created_at, created_by, deleted_at) VALUES (' +
      [
        literal(island.id),
        literal(island.no),
        literal(island.theme ?? island.id),
        literal(island.name?.zh),
        literal(island.name?.en),
        literal(island.summary?.zh),
        literal(island.summary?.en),
        literal(island.icon),
        Number.isFinite(island.color) ? String(island.color) : 'NULL',
        island.ang === null || island.ang === undefined ? 'NULL' : String(island.ang),
        '22',
        literal('seed'),
        'NULL',
        String(SEED_AT),
        'NULL',
        'NULL',
      ].join(', ') + ');'
    );
  }
  lines.push('');

  lines.push('-- items');
  for (const [id, item] of itemEntries) {
    lines.push(
      'INSERT OR REPLACE INTO items ' +
      '(id, island_id, no, model, name_zh, name_en, facts_json, timeline_json, src, freq, created_at, created_by, deleted_at) VALUES (' +
      [
        literal(id),
        literal(item.isl),
        String(item.no),
        literal(item.model),
        literal(item.name?.zh),
        literal(item.name?.en),
        jsonLiteral(item.facts ?? []),
        jsonLiteral(item.timeline ?? []),
        literal(item.src),
        literal(item.freq),
        String(SEED_AT),
        'NULL',
        'NULL',
      ].join(', ') + ');'
    );
  }
  lines.push('');

  lines.push('-- flows');
  for (const flow of FLOWS) {
    lines.push(
      'INSERT OR REPLACE INTO flows ' +
      '(id, from_island, to_island, kind, ev, updated, depts, carry_zh, carry_en, icon, note_zh, note_en, created_at, created_by, deleted_at) VALUES (' +
      [
        literal(flow.id),
        literal(flow.from),
        literal(flow.to),
        literal(flow.kind),
        literal(flow.ev),
        literal(flow.updated),
        Number.isFinite(flow.depts) ? String(flow.depts) : 'NULL',
        literal(flow.carry?.zh),
        literal(flow.carry?.en),
        literal(flow.icon),
        literal(flow.note?.zh),
        literal(flow.note?.en),
        String(SEED_AT),
        'NULL',
        'NULL',
      ].join(', ') + ');'
    );
  }
  lines.push('');

  lines.push('-- world metadata');
  lines.push("INSERT OR REPLACE INTO world_meta (k, v) VALUES ('seq', '0');");
  lines.push("INSERT OR REPLACE INTO world_meta (k, v) VALUES ('version', '1');");
  lines.push(`INSERT OR REPLACE INTO world_meta (k, v) VALUES ('seeded_at', '${SEED_AT}');`);
  lines.push('');

  return {
    sql: lines.join('\n'),
    counts: { islands: ISLANDS.length, items: itemEntries.length, flows: FLOWS.length },
  };
}

async function main() {
  const { sql, counts } = await buildSeedSQL();
  await mkdir(path.dirname(OUT_FILE), { recursive: true });
  await writeFile(OUT_FILE, sql, 'utf8');
  console.log(`SEED islands=${counts.islands} items=${counts.items} flows=${counts.flows}`);
  console.log(`WROTE ${path.relative(ROOT, OUT_FILE)} (${Buffer.byteLength(sql, 'utf8')} bytes)`);
}

const invokedDirectly = process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;

if (invokedDirectly) {
  main().catch((err) => {
    console.error(`SEED FAILED: ${err.message}`);
    process.exitCode = 1;
  });
}
